#!/usr/bin/env python3
"""Generate deterministic command mirrors and synchronize RCoder plugin versions."""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
CANONICAL_COMMANDS_DIR = ROOT / "skills" / "rcoder" / "commands"
COMMANDS_DIR = ROOT / "commands"
GEMINI_CMD_DIR = COMMANDS_DIR / "rcoder"
SKILL_MD = ROOT / "skills" / "rcoder" / "SKILL.md"
MARKDOWN_MARKER = "# AUTO-GENERATED — DO NOT EDIT DIRECTLY"
TOML_MARKER = "# AUTO-GENERATED BY scripts/sync_plugins.py — DO NOT EDIT DIRECTLY"
DESCRIPTION_RE = re.compile(r"^description:\s*(.*?)\s*$", re.M)
VERSION_RE = re.compile(r"^(?:version|  version):\s*['\"]?([0-9]+\.[0-9]+\.[0-9]+(?:[-+][A-Za-z0-9.-]+)?)['\"]?\s*$", re.M)

# JSON paths to the version fields owned by SKILL.md's metadata.version.
MANIFEST_VERSION_FIELDS: dict[Path, tuple[tuple[str | int, ...], ...]] = {
    ROOT / "package.json": (("version",),),
    ROOT / "plugin.json": (("version",),),
    ROOT / ".claude-plugin" / "plugin.json": (("version",),),
    ROOT / ".claude-plugin" / "marketplace.json": (("plugins", 0, "version"),),
    ROOT / ".codex-plugin" / "plugin.json": (("version",),),
    ROOT / "gemini-extension.json": (("version",),),
}
REQUIRED_MANIFESTS = (
    ROOT / "package.json",
    ROOT / "plugin.json",
    ROOT / ".claude-plugin" / "plugin.json",
    ROOT / ".claude-plugin" / "marketplace.json",
    ROOT / ".codex-plugin" / "plugin.json",
    ROOT / "gemini-extension.json",
    ROOT / ".agents" / "plugins" / "marketplace.json",
    ROOT / ".opencode" / "plugins" / "rcoder.js",
    ROOT / "mcp.json",
    ROOT / ".mcp.json",
)


def normalize_lf(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


def read_utf8_lf(path: Path) -> str:
    return normalize_lf(path.read_bytes().decode("utf-8"))


def parse_frontmatter(text: str) -> tuple[dict[str, str], str]:
    normalized = normalize_lf(text)
    if not normalized.startswith("---\n"):
        return {}, normalized.strip() + "\n"
    end = normalized.find("\n---\n", 4)
    if end < 0:
        raise ValueError("canonical command has unterminated YAML frontmatter")
    header = normalized[4:end]
    body = normalized[end + 5:].strip() + "\n"
    metadata: dict[str, str] = {}
    current_key: str | None = None
    for line in header.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line.startswith((" ", "\t")) and current_key:
            metadata[current_key] = (metadata[current_key] + " " + line.strip()).strip()
            continue
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        current_key = key.strip()
        value = value.strip()
        metadata[current_key] = "" if value in {">", "|", ">-", "|-"} else value.strip("'\"")
    return metadata, body


def render_markdown(source: str) -> str:
    normalized = normalize_lf(source)
    lines = normalized.splitlines(keepends=True)
    if not lines or lines[0].strip() != "---":
        raise ValueError("canonical command must start with YAML frontmatter")
    try:
        closing = next(index for index in range(1, len(lines)) if lines[index].strip() == "---")
    except StopIteration as error:
        raise ValueError("canonical command has unterminated YAML frontmatter") from error
    if not any(MARKDOWN_MARKER in line for line in lines[1:closing]):
        lines.insert(closing, MARKDOWN_MARKER + "\n")
    result = "".join(lines)
    return result if result.endswith("\n") else result + "\n"


def escape_toml_basic(value: str) -> str:
    return (value.replace("\\", "\\\\").replace('"', '\\"')
            .replace("\b", "\\b").replace("\t", "\\t")
            .replace("\n", " ").replace("\r", " ").replace("\f", "\\f"))


def escape_toml_multiline(value: str) -> str:
    # A backslash before the first quote makes a triple-quote sequence literal in TOML.
    return value.replace("\\", "\\\\").replace('"""', '\\"""').rstrip("\n")


def render_toml(slug: str, metadata: dict[str, str], body: str) -> str:
    description = metadata.get("description") or f"Run RCoder {slug} workflow"
    prompt = f"{body.rstrip()}\n\nUser request / target arguments: {{{{args}}}}\n"
    return (
        f"{TOML_MARKER}\n"
        f'description = "{escape_toml_basic(description)}"\n'
        f'prompt = """\n{escape_toml_multiline(prompt)}\n"""\n'
    )


def write_or_check(path: Path, expected: str, check_only: bool, drifts: list[str]) -> None:
    expected_bytes = normalize_lf(expected).encode("utf-8")
    relative = path.relative_to(ROOT).as_posix()
    try:
        actual = path.read_bytes()
    except FileNotFoundError:
        drifts.append(f"MISSING: {relative}")
        if not check_only:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected_bytes)
        return
    if actual != expected_bytes:
        drifts.append(f"DRIFT: {relative}")
        if not check_only:
            path.write_bytes(expected_bytes)


def set_nested(data: dict[str, Any], path: tuple[str | int, ...], value: str) -> bool:
    current: Any = data
    for part in path[:-1]:
        if isinstance(part, int):
            if not isinstance(current, list) or part >= len(current):
                return False
            current = current[part]
        else:
            if not isinstance(current, dict) or part not in current:
                return False
            current = current[part]
    last = path[-1]
    if isinstance(last, int):
        if not isinstance(current, list) or last >= len(current):
            return False
        current[last] = value
    else:
        if not isinstance(current, dict) or last not in current:
            return False
        current[last] = value
    return True


def get_nested(data: dict[str, Any], path: tuple[str | int, ...]) -> Any:
    current: Any = data
    for part in path:
        if isinstance(part, int):
            if not isinstance(current, list) or part >= len(current):
                return None
            current = current[part]
        else:
            if not isinstance(current, dict):
                return None
            current = current.get(part)
    return current


def sync_manifest_versions(version: str, check_only: bool, drifts: list[str]) -> None:
    for manifest, fields in MANIFEST_VERSION_FIELDS.items():
        if not manifest.is_file():
            continue
        try:
            data = json.loads(read_utf8_lf(manifest))
        except (OSError, json.JSONDecodeError) as error:
            raise ValueError(f"invalid manifest JSON in {manifest.relative_to(ROOT)}: {error}") from error
        if not isinstance(data, dict):
            raise ValueError(f"manifest root must be an object: {manifest.relative_to(ROOT)}")
        changed = False
        for field in fields:
            current = get_nested(data, field)
            if current is None:
                raise ValueError(f"missing version field {field!r} in {manifest.relative_to(ROOT)}")
            if current != version:
                drifts.append(f"VERSION_DRIFT ({current} != {version}): {manifest.relative_to(ROOT)}")
                changed = set_nested(data, field, version) or changed
        if changed and not check_only:
            manifest.write_bytes((json.dumps(data, indent=2, ensure_ascii=False) + "\n").encode("utf-8"))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail without writing when generated files drift")
    args = parser.parse_args()
    if not CANONICAL_COMMANDS_DIR.is_dir():
        print(f"[sync_plugins] ERROR: canonical command directory not found: {CANONICAL_COMMANDS_DIR}",
              file=sys.stderr)
        return 1
    if not SKILL_MD.is_file():
        print("[sync_plugins] ERROR: skills/rcoder/SKILL.md is missing", file=sys.stderr)
        return 1

    drifts: list[str] = []
    try:
        canonical_files = sorted(CANONICAL_COMMANDS_DIR.glob("*.md"))
        expected_slugs = {path.stem for path in canonical_files}
        for source in canonical_files:
            raw = read_utf8_lf(source)
            metadata, body = parse_frontmatter(raw)
            write_or_check(COMMANDS_DIR / source.name, render_markdown(raw), args.check, drifts)
            write_or_check(GEMINI_CMD_DIR / f"{source.stem}.toml",
                           render_toml(source.stem, metadata, body), args.check, drifts)

        for directory, suffix in ((COMMANDS_DIR, ".md"), (GEMINI_CMD_DIR, ".toml")):
            for stale in sorted(directory.glob(f"*{suffix}")):
                if stale.stem in expected_slugs:
                    continue
                try:
                    generated = MARKDOWN_MARKER in read_utf8_lf(stale) or TOML_MARKER in read_utf8_lf(stale)
                except (OSError, UnicodeDecodeError):
                    generated = False
                if generated:
                    drifts.append(f"ORPHAN: {stale.relative_to(ROOT).as_posix()}")
                    if not args.check:
                        stale.unlink()

        missing = [path.relative_to(ROOT).as_posix() for path in REQUIRED_MANIFESTS if not path.is_file()]
        if missing:
            raise ValueError("missing required manifests/components: " + ", ".join(missing))
        skill_text = read_utf8_lf(SKILL_MD)
        match = VERSION_RE.search(skill_text.split("---", 2)[1] if skill_text.startswith("---") else "")
        if not match:
            raise ValueError("SKILL.md metadata.version must be a semantic version")
        sync_manifest_versions(match.group(1), args.check, drifts)
    except (OSError, UnicodeDecodeError, ValueError, json.JSONDecodeError) as error:
        print(f"[sync_plugins] ERROR: {error}", file=sys.stderr)
        return 1

    if drifts:
        mode = "CHECK FAILED" if args.check else "SYNCHRONIZED"
        print(f"[sync_plugins] {mode} ({len(drifts)} item(s)):")
        for item in drifts:
            print(f"  - {item}")
        return 1 if args.check else 0
    print(f"[sync_plugins] OK — {len(canonical_files)} commands, manifests, and generated mirrors are in sync.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
